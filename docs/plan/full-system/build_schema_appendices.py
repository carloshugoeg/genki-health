 for (e,en),tid in owner.items():
  if e!=engine or en in existing:continue
  fields=es[en];pk=[n for n,v in fields.items() if 'PK' in v['key']];assert pk,en
  cols=[];generated=[]
  if 'id_institucion' not in fields:cols.append(' id_institucion INTEGER NOT NULL')
  for n,v in fields.items():
   typ=v['type'].replace('INT','INTEGER') if v['type']=='INT' else v['type']
   if typ=='TIMESTAMP':typ='TIMESTAMPTZ' if engine=='postgres' else 'DATETIME(3)'
   if typ.startswith('JSON'):typ='JSONB' if engine=='postgres' else 'JSON'
   if typ.startswith('DECIMAL') and engine=='postgres':typ=typ.replace('DECIMAL','NUMERIC')
   gen=len(pk)==1 and n in pk and v['type'] in ['INT','BIGINT'] and 'FK' not in v['key'] and ('Autoincremental' in v['rule'] or (v['source_line'] in [1433,1477] and n.startswith('id_')))
   if gen:generated.append(n)
   clause=(' GENERATED BY DEFAULT AS IDENTITY' if engine=='postgres' else ' AUTO_INCREMENT') if gen else ''
   cols.append(f' {n} {typ}{clause}'+(' NOT NULL' if v['required'] else ''))
  if engine=='mysql':
   for n in generated:cols.append(f' UNIQUE ({n})')
  cols.append(' PRIMARY KEY ('+', '.join(dict.fromkeys(['id_institucion']+pk))+')')
  out.append(f'\n-- Owner {tid}; source entity {en}\nCREATE TABLE {en.lower()} (\n'+',\n'.join(cols)+'\n)'+(' ENGINE=InnoDB' if engine=='mysql' else '')+';\n')
 (F/'contracts'/f'NEW-TABLES-{engine}.sql').write_text(''.join(out))
