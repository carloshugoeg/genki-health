-- FS-02-PG01: permiso / rol_permiso / bitacora (Hospital PostgreSQL identity SoR).
CREATE TABLE IF NOT EXISTS permiso (
  id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(60) NOT NULL UNIQUE,
  descripcion VARCHAR(200) NOT NULL,
  nivel_dato VARCHAR(15) NOT NULL
);

CREATE TABLE IF NOT EXISTS rol_permiso (
  id_rol INTEGER NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
  id_permiso INTEGER NOT NULL REFERENCES permiso(id_permiso) ON DELETE RESTRICT,
  PRIMARY KEY (id_rol, id_permiso)
);

CREATE TABLE IF NOT EXISTS bitacora (
  id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  entidad VARCHAR(40) NOT NULL,
  id_registro VARCHAR(40) NOT NULL,
  accion VARCHAR(15) NOT NULL,
  fecha_hora TIMESTAMPTZ NOT NULL,
  direccion_ip VARCHAR(45),
  detalle JSONB
);

CREATE INDEX IF NOT EXISTS ix_bitacora_tiempo ON bitacora (fecha_hora DESC, id_bitacora DESC);
CREATE INDEX IF NOT EXISTS ix_bitacora_entidad ON bitacora (entidad, id_registro);
ALTER TABLE bitacora
  ADD COLUMN IF NOT EXISTS id_institucion INTEGER REFERENCES institucion(id_institucion);
CREATE INDEX IF NOT EXISTS ix_bitacora_institucion
  ON bitacora (id_institucion, fecha_hora, id_bitacora);
