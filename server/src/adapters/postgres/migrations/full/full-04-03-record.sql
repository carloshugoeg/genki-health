-- FS-04-PG03: append-only audit for OP-19 reactivation (never erase clinical history).
CREATE TABLE IF NOT EXISTS reactivacion_audit (
  id_institucion INTEGER NOT NULL,
  id_reactivacion BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_expediente INTEGER NOT NULL,
  id_usuario INTEGER NOT NULL,
  motivo VARCHAR(300) NOT NULL,
  fecha_hora TIMESTAMPTZ NOT NULL,
  fecha_archivo_previa TIMESTAMPTZ,
  motivo_archivo_previo VARCHAR(20),
  observacion_archivo_previa VARCHAR(500),
  PRIMARY KEY (id_institucion, id_reactivacion)
);
