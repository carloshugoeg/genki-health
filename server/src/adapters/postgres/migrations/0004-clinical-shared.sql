DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT conname
      FROM pg_constraint
     WHERE conrelid = 'consulta'::regclass
       AND contype = 'c'
  LOOP
    EXECUTE format('ALTER TABLE consulta DROP CONSTRAINT %I', r.conname);
  END LOOP;
END $$;

