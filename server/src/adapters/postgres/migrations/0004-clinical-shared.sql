CREATE TABLE IF NOT EXISTS antecedente (
  id_institucion INTEGER NOT NULL,
  id_antecedente INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_expediente INTEGER NOT NULL REFERENCES expediente (id_expediente) ON DELETE RESTRICT,
  tipo VARCHAR(20) NOT NULL,
  descripcion VARCHAR(300) NOT NULL,
  fecha_inicio DATE,
  vigente BOOLEAN NOT NULL,
  fecha_registro TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (id_institucion, id_antecedente),
  CHECK (tipo IN ('personal', 'familiar', 'quirurgico', 'habito'))
);

CREATE TABLE IF NOT EXISTS alergia (
  id_institucion INTEGER NOT NULL,
  id_alergia INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_expediente INTEGER NOT NULL REFERENCES expediente (id_expediente) ON DELETE RESTRICT,
  sustancia VARCHAR(120) NOT NULL,
  sustancia_norm VARCHAR(120) NOT NULL,
  tipo VARCHAR(20) NOT NULL,
  severidad VARCHAR(15) NOT NULL,
  reaccion VARCHAR(200),
  fecha_deteccion DATE,
  PRIMARY KEY (id_institucion, id_alergia),
  UNIQUE (id_institucion, id_expediente, sustancia_norm),
  CHECK (tipo IN ('medicamento', 'alimento', 'ambiental', 'otro')),
  CHECK (severidad IN ('leve', 'moderada', 'severa'))
);

CREATE TABLE IF NOT EXISTS documento_adjunto (
  id_institucion INTEGER NOT NULL,
  id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_expediente INTEGER NOT NULL REFERENCES expediente (id_expediente) ON DELETE RESTRICT,
  id_consulta INTEGER REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  nombre_archivo VARCHAR(160) NOT NULL,
  tipo_mime VARCHAR(60) NOT NULL,
  ruta VARCHAR(300) NOT NULL,
  hash_sha256 CHAR(64) NOT NULL,
  fecha_carga TIMESTAMPTZ NOT NULL,
  contenido BYTEA NOT NULL,
  PRIMARY KEY (id_institucion, id_documento)
);

CREATE TABLE IF NOT EXISTS signos_vitales (
  id_institucion INTEGER NOT NULL,
  id_signos INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_consulta INTEGER NOT NULL REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  fecha_hora_toma TIMESTAMPTZ NOT NULL,
  presion_sistolica SMALLINT,
  presion_diastolica SMALLINT,
  frecuencia_cardiaca SMALLINT,
  frecuencia_respiratoria SMALLINT,
  temperatura_c NUMERIC(4, 1),
  saturacion_oxigeno SMALLINT,
  peso_kg NUMERIC(5, 2),
  talla_cm NUMERIC(5, 1),
  PRIMARY KEY (id_institucion, id_signos),
  UNIQUE (id_institucion, id_consulta)
);

CREATE TABLE IF NOT EXISTS consulta_borrador (
  id_institucion INTEGER NOT NULL,
  id_consulta INTEGER NOT NULL REFERENCES consulta (id_consulta) ON DELETE RESTRICT,
  bundle JSONB NOT NULL,
  revision INTEGER NOT NULL,
  PRIMARY KEY (id_institucion, id_consulta)
);
