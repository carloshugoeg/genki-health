-- Identity SoR only on Hospital PostgreSQL; other engines store no login credentials.
CREATE TABLE rol (id_rol INTEGER PRIMARY KEY, nombre VARCHAR(40) NOT NULL UNIQUE, descripcion TEXT);
CREATE TABLE usuario (
 id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_institucion INTEGER NOT NULL REFERENCES institucion(id_institucion) ON DELETE RESTRICT,
 id_profesional INTEGER REFERENCES profesional(id_profesional) ON DELETE RESTRICT,
 id_rol INTEGER NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
 nombre_usuario VARCHAR(80) NOT NULL UNIQUE, correo VARCHAR(120) NOT NULL UNIQUE,
 hash_contrasena TEXT NOT NULL, estado VARCHAR(12) NOT NULL CHECK(estado IN ('activo','bloqueado','inactivo')),
 intentos_fallidos INTEGER NOT NULL DEFAULT 0 CHECK(intentos_fallidos>=0), ultimo_acceso TIMESTAMPTZ
);
-- Infrastructure session table, not a new clinical entity. Stores hashed jti, never JWT/password.
CREATE TABLE auth_session (
 jti_hash CHAR(64) PRIMARY KEY, id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
 expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL, revoked_at TIMESTAMPTZ
);
CREATE INDEX ix_auth_session_usuario ON auth_session(id_usuario,expires_at);
