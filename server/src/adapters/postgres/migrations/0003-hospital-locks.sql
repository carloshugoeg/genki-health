-- Locked E1-06 hospital-only structural appendix. No live admission/note routes.
CREATE TABLE servicio (id_servicio INTEGER PRIMARY KEY, nombre VARCHAR(80) NOT NULL UNIQUE, piso VARCHAR(20), activo BOOLEAN NOT NULL);
CREATE TABLE servicio_facturable (
 codigo_servicio VARCHAR(30) PRIMARY KEY, id_institucion INTEGER NOT NULL REFERENCES institucion(id_institucion),
 nombre VARCHAR(120) NOT NULL, tipo VARCHAR(30) NOT NULL, precio_unitario NUMERIC(10,2) NOT NULL CHECK(precio_unitario>=0),
 unidad VARCHAR(30) NOT NULL, afecto_iva BOOLEAN NOT NULL, vigente BOOLEAN NOT NULL
);
CREATE TABLE cama (
 id_cama INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_servicio INTEGER NOT NULL REFERENCES servicio(id_servicio) ON DELETE RESTRICT,
 codigo VARCHAR(10) NOT NULL, tipo_cama VARCHAR(25) NOT NULL,
 codigo_servicio VARCHAR(30) NOT NULL REFERENCES servicio_facturable(codigo_servicio) ON DELETE RESTRICT,
 estado VARCHAR(15) NOT NULL CHECK(estado IN ('libre','ocupada','mantenimiento')),
 UNIQUE(id_servicio,codigo)
);
CREATE TABLE admision (
 id_admision INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_expediente INTEGER NOT NULL REFERENCES expediente(id_expediente) ON DELETE RESTRICT,
 id_consulta_origen INTEGER REFERENCES consulta(id_consulta) ON DELETE RESTRICT,
 id_cama INTEGER NOT NULL REFERENCES cama(id_cama) ON DELETE RESTRICT,
 id_diagnostico_ingreso INTEGER NOT NULL REFERENCES diagnostico(id_diagnostico) ON DELETE RESTRICT,
 id_diagnostico_egreso INTEGER REFERENCES diagnostico(id_diagnostico) ON DELETE RESTRICT,
 tipo_ingreso VARCHAR(20) NOT NULL, fecha_hora_ingreso TIMESTAMPTZ NOT NULL,
 fecha_hora_egreso TIMESTAMPTZ, condicion_egreso VARCHAR(30), estado VARCHAR(15) NOT NULL,
 CHECK(fecha_hora_egreso IS NULL OR fecha_hora_egreso>=fecha_hora_ingreso)
);
CREATE TABLE nota_evolucion (
 id_nota INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_admision INTEGER NOT NULL REFERENCES admision(id_admision) ON DELETE RESTRICT,
 id_profesional INTEGER NOT NULL REFERENCES profesional(id_profesional) ON DELETE RESTRICT,
 id_nota_anterior INTEGER REFERENCES nota_evolucion(id_nota) ON DELETE RESTRICT,
 fecha_hora TIMESTAMPTZ NOT NULL, contenido TEXT NOT NULL, turno VARCHAR(10),
 CHECK(id_nota_anterior IS NULL OR id_nota_anterior<>id_nota)
);
CREATE UNIQUE INDEX uq_admision_activa_expediente ON admision(id_expediente) WHERE estado='activa';
CREATE UNIQUE INDEX uq_admision_activa_cama ON admision(id_cama) WHERE estado='activa';
CREATE INDEX ix_nota_admision_fecha ON nota_evolucion(id_admision,fecha_hora,id_nota);
CREATE INDEX ix_nota_anterior ON nota_evolucion(id_nota_anterior);
CREATE VIEW reporte_pacientes AS SELECT id_institucion,estado,COUNT(*) AS cantidad FROM paciente GROUP BY id_institucion,estado;
