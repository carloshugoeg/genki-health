-- OP37 procedure catalog + rows (Hospital PG). Idempotent.
CREATE TABLE IF NOT EXISTS catalogo_procedimiento (
  codigo_procedimiento VARCHAR(10) PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  categoria VARCHAR(40) NOT NULL,
  duracion_estimada_min SMALLINT
);

CREATE TABLE IF NOT EXISTS procedimiento (
  id_procedimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_admision INTEGER REFERENCES admision(id_admision) ON DELETE RESTRICT,
  id_consulta INTEGER REFERENCES consulta(id_consulta) ON DELETE RESTRICT,
  codigo_procedimiento VARCHAR(10) NOT NULL REFERENCES catalogo_procedimiento(codigo_procedimiento) ON DELETE RESTRICT,
  id_profesional INTEGER NOT NULL REFERENCES profesional(id_profesional) ON DELETE RESTRICT,
  fecha_hora TIMESTAMPTZ NOT NULL,
  sala VARCHAR(20),
  hallazgos TEXT,
  complicaciones TEXT,
  equipo JSONB NOT NULL DEFAULT '[]'::jsonb,
  consumos JSONB NOT NULL DEFAULT '[]'::jsonb,
  CHECK (
    (id_admision IS NOT NULL AND id_consulta IS NULL)
    OR (id_admision IS NULL AND id_consulta IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS ix_procedimiento_admision ON procedimiento(id_admision);
CREATE INDEX IF NOT EXISTS ix_procedimiento_consulta ON procedimiento(id_consulta);

