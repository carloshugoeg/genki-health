#!/usr/bin/env bash
# Create repository-root .env once with independent random secrets. Never print values.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${GENKI_ENV_FILE:-$ROOT/.env}"

if [[ -e "$ENV_FILE" ]]; then
  echo "demo-env: exists (not overwritten): $(basename "$ENV_FILE")"
  exit 0
fi

umask 077

rand() {
  # 48 bytes → 64 url-safe chars; enough for JWT_SECRET (>=32) and DB passwords.
  openssl rand -base64 48 | tr -d '\n' | tr '+/' '-_'
}

JWT_SECRET="$(rand)"
SEED_PASSWORD="$(rand)"
POSTGRES_PASSWORD="$(rand)"
MYSQL_ROOT_PASSWORD="$(rand)"
MYSQL_PASSWORD="$(rand)"
MONGO_ROOT_PASSWORD="$(rand)"
MONGO_APP_PASSWORD="$(rand)"
MONGO_REPORT_PASSWORD="$(rand)"
APP_DB_PASSWORD="$(rand)"
IDENTITY_DB_PASSWORD="$(rand)"
REPORT_DB_PASSWORD="$(rand)"

HOST=127.0.0.1
PG_PORT=5432
MYSQL_PORT=3306
MONGO_PORT=27017
FIRESTORE_PORT=8080
PROJECT=demo-genki-health

cat >"$ENV_FILE" <<EOF
NODE_ENV=development
API_HOST=127.0.0.1
API_PORT=3000
GENKI_MODE=memory

JWT_SECRET=${JWT_SECRET}
SEED_PASSWORD=${SEED_PASSWORD}

POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD}
MYSQL_PASSWORD=${MYSQL_PASSWORD}
MONGO_ROOT_PASSWORD=${MONGO_ROOT_PASSWORD}
MONGO_APP_PASSWORD=${MONGO_APP_PASSWORD}
MONGO_REPORT_PASSWORD=${MONGO_REPORT_PASSWORD}
APP_DB_PASSWORD=${APP_DB_PASSWORD}
IDENTITY_DB_PASSWORD=${IDENTITY_DB_PASSWORD}
REPORT_DB_PASSWORD=${REPORT_DB_PASSWORD}

POSTGRES_HOST=${HOST}
POSTGRES_PORT=${PG_PORT}
POSTGRES_DB=genki_hospital
POSTGRES_USER=genki

MYSQL_HOST=${HOST}
MYSQL_PORT=${MYSQL_PORT}
MYSQL_DATABASE=genki_pediatrico
MYSQL_USER=genki

DATABASE_URL=postgres://genki:${POSTGRES_PASSWORD}@${HOST}:${PG_PORT}/genki_hospital
AUTH_DATABASE_URL=postgres://genki_identity:${IDENTITY_DB_PASSWORD}@${HOST}:${PG_PORT}/genki_hospital
PG_ADMIN_URL=postgres://genki:${POSTGRES_PASSWORD}@${HOST}:${PG_PORT}/postgres
MYSQL_URL=mysql://genki:${MYSQL_PASSWORD}@${HOST}:${MYSQL_PORT}/genki_pediatrico
MYSQL_ADMIN_URL=mysql://root:${MYSQL_ROOT_PASSWORD}@${HOST}:${MYSQL_PORT}/
MONGODB_URI=mongodb://genkiApp:${MONGO_APP_PASSWORD}@${HOST}:${MONGO_PORT}/genki_laboratorio?authSource=genki_laboratorio&replicaSet=rs0
MONGO_ADMIN_URI=mongodb://root:${MONGO_ROOT_PASSWORD}@${HOST}:${MONGO_PORT}/admin?replicaSet=rs0&directConnection=true

FIRESTORE_EMULATOR_HOST=${HOST}:${FIRESTORE_PORT}
GCLOUD_PROJECT=${PROJECT}
FIREBASE_PROJECT_ID=${PROJECT}
EOF

chmod 0600 "$ENV_FILE"

echo "demo-env: created names:"
echo "JWT_SECRET SEED_PASSWORD POSTGRES_PASSWORD MYSQL_ROOT_PASSWORD MYSQL_PASSWORD"
echo "MONGO_ROOT_PASSWORD MONGO_APP_PASSWORD MONGO_REPORT_PASSWORD"
echo "APP_DB_PASSWORD IDENTITY_DB_PASSWORD REPORT_DB_PASSWORD"
echo "DATABASE_URL AUTH_DATABASE_URL PG_ADMIN_URL MYSQL_URL MYSQL_ADMIN_URL MONGODB_URI MONGO_ADMIN_URI"
echo "FIRESTORE_EMULATOR_HOST GCLOUD_PROJECT GENKI_MODE"
